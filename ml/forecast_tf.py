"""OPTIONAL: TensorFlow forecaster for nitrogen N(t + horizon).

Trains a small dense network on data generated by the simulator and reports its error
against the physics model. Requires `pip install tensorflow` (not in requirements.txt
because it is large). This script is provided as the ML extension described in the project
write-up; it has not been run in this repository's CI. The calibrated physics model
(backend/dot/calibration.py) is what the live backend uses.

    python ml/forecast_tf.py --horizon 8 --epochs 30
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from dot.simulator import Biome  # noqa: E402

FEATURES = ["nitrogen", "injection", "uptake", "moisture", "ph", "temperature", "radiation", "biomass"]


def make_dataset(horizon: int, runs: int = 40, steps: int = 500):
    xs, ys = [], []
    for seed in range(runs):
        b = Biome(seed=seed, n=30.0 + 3.0 * seed)
        rows = [b.tick(0.25) for _ in range(steps)]
        for k in range(len(rows) - horizon):
            xs.append([rows[k][f] for f in FEATURES])
            ys.append(rows[k + horizon]["nitrogen"])
    return np.asarray(xs, dtype="float32"), np.asarray(ys, dtype="float32")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--horizon", type=int, default=8, help="steps ahead (each step = 0.25 h)")
    ap.add_argument("--epochs", type=int, default=30)
    args = ap.parse_args()
    import tensorflow as tf  # imported lazily so the rest of the repo needs no TensorFlow

    x, y = make_dataset(args.horizon)
    split = int(0.8 * len(x))
    mean, std = x[:split].mean(0), x[:split].std(0) + 1e-6
    model = tf.keras.Sequential([
        tf.keras.layers.Input(shape=(len(FEATURES),)),
        tf.keras.layers.Normalization(mean=mean, variance=std ** 2),
        tf.keras.layers.Dense(64, activation="relu"),
        tf.keras.layers.Dense(32, activation="relu"),
        tf.keras.layers.Dense(1),
    ])
    model.compile(optimizer="adam", loss="mse", metrics=["mae"])
    model.fit(x[:split], y[:split], validation_data=(x[split:], y[split:]), epochs=args.epochs, batch_size=128, verbose=2)
    mae = float(model.evaluate(x[split:], y[split:], verbose=0)[1])
    print(f"validation MAE for N(t+{args.horizon * 0.25:g} h): {mae:.2f} mg/kg")
    model.save(Path(__file__).with_name("n_forecaster.keras"))


if __name__ == "__main__":
    main()
